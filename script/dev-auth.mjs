import { randomBytes } from "node:crypto";
import { execFile, spawn } from "node:child_process";
import { promisify } from "node:util";
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const mode = String(process.argv[2] || "").toLowerCase();
if (!["stream", "admin"].includes(mode)) {
  console.error("Use: node script/dev-auth.mjs stream|admin");
  process.exit(1);
}

const root = process.cwd();
const varsPath = path.join(root, ".dev.vars");
const statePath = path.join(root, ".wrangler", "state");
const seedPath = path.join(root, ".wrangler", "dev-seed", "stream");
const launcherPath = path.join(root, ".wrangler", "ballsville-dev-launcher.json");
const nextEntry = path.join(root, "node_modules", "next", "dist", "bin", "next");
const wranglerEntry = path.join(root, "node_modules", "wrangler", "bin", "wrangler.js");
const preferredNextPort = Number(process.env.BALLSVILLE_DEV_NEXT_PORT || "3000");
const preferredProxyPort = Number(process.env.BALLSVILLE_DEV_PROXY_PORT || "8788");
const skipBrowser = process.env.BALLSVILLE_DEV_SKIP_BROWSER === "1";
const skipSync = process.env.BALLSVILLE_DEV_SKIP_SYNC === "1";
const execFileAsync = promisify(execFile);
const children = [];
let nextPort = preferredNextPort;
let proxyPort = preferredProxyPort;

function normalized(value) {
  return path.resolve(String(value || "")).replaceAll("\\", "/").toLowerCase();
}

function parseVars(source) {
  const values = new Map();
  for (const line of String(source || "").split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (match) values.set(match[1], match[2].replace(/^(['"])(.*)\1$/, "$2"));
  }
  return values;
}

async function ensureLocalAuth() {
  let source = "";
  try { source = await fs.readFile(varsPath, "utf8"); } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  const values = parseVars(source);
  const additions = [];
  for (const prefix of ["STREAM", "ADMIN"]) {
    if (!values.get(`${prefix}_AUTH_SECRET`)) additions.push(`${prefix}_AUTH_SECRET="${randomBytes(48).toString("base64url")}"`);
    if (!values.get(`${prefix}_APPROVAL_DEV_MODE`)) additions.push(`${prefix}_APPROVAL_DEV_MODE="true"`);
    if (!values.get(`${prefix}_PUBLIC_ORIGIN`)) additions.push(`${prefix}_PUBLIC_ORIGIN="http://localhost:8788"`);
  }
  if (additions.length) {
    const separator = source && !source.endsWith("\n") ? "\n" : "";
    await fs.appendFile(varsPath, `${separator}\n# Generated by npm run dev:${mode}\n${additions.join("\n")}\n`, "utf8");
    console.log("Added missing local Stream/Admin authentication settings to .dev.vars.");
  }
}

function run(command, args, options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd: root, stdio: "inherit", ...options });
    child.once("error", reject);
    child.once("exit", (code) => code === 0 ? resolve() : reject(new Error(`${command} exited with code ${code}`)));
  });
}

async function listenerPids(port) {
  if (process.platform !== "win32") {
    try {
      const { stdout } = await execFileAsync("lsof", ["-ti", `tcp:${port}`, "-sTCP:LISTEN"]);
      return [...new Set(stdout.split(/\s+/).map(Number).filter(Boolean))];
    } catch { return []; }
  }
  const { stdout } = await execFileAsync("netstat.exe", ["-ano", "-p", "TCP"]);
  const wanted = Number(port);
  const pids = [];
  for (const line of stdout.split(/\r?\n/)) {
    const columns = line.trim().split(/\s+/);
    if (columns.length < 5 || String(columns[3]).toUpperCase() !== "LISTENING") continue;
    const match = String(columns[1]).match(/:(\d+)$/);
    if (Number(match?.[1]) === wanted) pids.push(Number(columns[4]));
  }
  return [...new Set(pids.filter(Boolean))];
}

async function isBallsvillePort(port) {
  try {
    const response = await fetch(`http://localhost:${port}/ballsville-dev-id.json`, {
      cache: "no-store", signal: AbortSignal.timeout(1500),
    });
    const identity = await response.json();
    return response.ok && identity?.project === "theballsvillegame.com" && identity?.devLauncher === 1;
  } catch { return false; }
}

async function terminateTree(pid) {
  if (!pid || pid === process.pid) return;
  if (process.platform === "win32") await execFileAsync("taskkill.exe", ["/pid", String(pid), "/t", "/f"]).catch(() => {});
  else { try { process.kill(pid, "SIGTERM"); } catch {} }
}

async function stopPriorLauncher() {
  let marker;
  try { marker = JSON.parse(await fs.readFile(launcherPath, "utf8")); } catch { return; }
  if (normalized(marker?.root) !== normalized(root) || Number(marker?.pid) === process.pid) return;
  const ownsMarkedPort = await isBallsvillePort(Number(marker.proxyPort)) || await isBallsvillePort(Number(marker.nextPort));
  if (!ownsMarkedPort) return;
  console.log(`Stopping the previous Ballsville ${marker.mode || "authenticated"} dev session...`);
  await terminateTree(Number(marker.pid));
}

async function choosePorts() {
  await stopPriorLauncher();
  for (let offset = 0; offset < 100; offset += 1) {
    const candidateNext = preferredNextPort + offset;
    const candidateProxy = preferredProxyPort + offset;
    const [nextPids, proxyPids] = await Promise.all([listenerPids(candidateNext), listenerPids(candidateProxy)]);
    const owners = [...new Set([...nextPids, ...proxyPids])];
    const [nextIsBallsville, proxyIsBallsville] = await Promise.all([
      nextPids.length ? isBallsvillePort(candidateNext) : false,
      proxyPids.length ? isBallsvillePort(candidateProxy) : false,
    ]);
    const hasUnrelatedOwner = (nextPids.length && !nextIsBallsville) || (proxyPids.length && !proxyIsBallsville);
    if (hasUnrelatedOwner) {
      if (offset === 0) console.log(`Ports ${candidateNext}/${candidateProxy} belong to another project; leaving it running.`);
      continue;
    }
    if (owners.length) {
      console.log(`Restarting existing Ballsville services on ports ${candidateNext}/${candidateProxy}...`);
      for (const pid of owners) await terminateTree(pid);
    }
    nextPort = candidateNext;
    proxyPort = candidateProxy;
    if (offset) console.log(`Using the next free ports: Next ${nextPort}, Cloudflare ${proxyPort}.`);
    return;
  }
  throw new Error("Could not find an available local port pair.");
}

async function writeLauncherMarker() {
  await fs.mkdir(path.dirname(launcherPath), { recursive: true });
  await fs.writeFile(launcherPath, JSON.stringify({ pid: process.pid, root, mode, nextPort, proxyPort }, null, 2), "utf8");
}

async function removeLauncherMarker() {
  try {
    const marker = JSON.parse(await fs.readFile(launcherPath, "utf8"));
    if (Number(marker.pid) === process.pid) await fs.unlink(launcherPath);
  } catch {}
}

async function syncStreamSnapshots() {
  const snapshots = [["injuries.json", "data/stream/injuries.json"], ["trades.json", "data/stream/trades.json"]];
  await fs.mkdir(seedPath, { recursive: true });
  console.log("Refreshing the local Stream snapshots from production...");
  for (const [fileName, objectKey] of snapshots) {
    const response = await fetch(`https://www.theballsvillegame.com/r2/${objectKey}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`${fileName} download returned ${response.status}`);
    const body = await response.text();
    JSON.parse(body);
    const filePath = path.join(seedPath, fileName);
    await fs.writeFile(filePath, body, "utf8");
    await run(process.execPath, [wranglerEntry, "r2", "object", "put", `admin/${objectKey}`, "--file", filePath, "--local", "--persist-to", statePath]);
  }
  console.log("Local Stream R2 data is current.");
}

async function reachable(url) {
  try {
    const response = await fetch(url, { signal: AbortSignal.timeout(1500), redirect: "manual" });
    return response.status > 0;
  } catch { return false; }
}

async function waitFor(url, label, timeoutMs = 90000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (await reachable(url)) return;
    await new Promise((resolve) => setTimeout(resolve, 750));
  }
  throw new Error(`${label} did not become available at ${url}`);
}

function start(command, args) {
  const child = spawn(command, args, { cwd: root, stdio: "inherit" });
  children.push(child);
  child.once("exit", (code) => { if (code && code !== 0) console.error(`${command} stopped with code ${code}.`); });
  return child;
}

function openBrowser(url) {
  if (process.platform === "win32") spawn("cmd.exe", ["/c", "start", "", url], { detached: true, stdio: "ignore", windowsHide: true }).unref();
  else if (process.platform === "darwin") spawn("open", [url], { detached: true, stdio: "ignore" }).unref();
  else spawn("xdg-open", [url], { detached: true, stdio: "ignore" }).unref();
}

async function stopChildren() {
  for (const child of children) {
    if (!child.pid || child.exitCode != null) continue;
    await terminateTree(child.pid);
  }
}

let stopping = false;
async function shutdown(code = 0) {
  if (stopping) return;
  stopping = true;
  await stopChildren();
  await removeLauncherMarker();
  process.exit(code);
}
process.once("SIGINT", () => shutdown(0));
process.once("SIGTERM", () => shutdown(0));

try {
  await ensureLocalAuth();
  await choosePorts();
  if (mode === "stream" && !skipSync) {
    try { await syncStreamSnapshots(); }
    catch (error) { console.warn(`Could not refresh Stream snapshots: ${error.message}. Existing local data will still be used.`); }
  }

  console.log(`Starting Next.js on port ${nextPort}...`);
  start(process.execPath, [nextEntry, "dev", "-p", String(nextPort)]);
  await waitFor(`http://localhost:${nextPort}`, "Next.js");

  console.log(`Starting the Cloudflare Pages proxy on port ${proxyPort}...`);
  start(process.execPath, [wranglerEntry, "pages", "dev", "--proxy", String(nextPort), "--port", String(proxyPort), "--persist-to", statePath]);
  await waitFor(`http://localhost:${proxyPort}`, "Cloudflare Pages proxy");
  await writeLauncherMarker();

  const target = `http://localhost:${proxyPort}${mode === "stream" ? "/stream" : "/admin/login"}`;
  console.log(`Opening ${target}`);
  if (!skipBrowser) openBrowser(target);
  console.log("Local authenticated development is running. Press Ctrl+C to stop it.");
  await new Promise(() => {});
} catch (error) {
  console.error(`Local ${mode} startup failed: ${error?.message || error}`);
  await shutdown(1);
}
